import { Pencil } from 'lucide-react';
import { formatFileSize } from '../utils/formatting.js';

function Block({ title, step, onEdit, children }) {
  return (
    <section className="card">
      <div className="mb-3 flex items-center justify-between">
        <h2 className="section-title !mb-0">{title}</h2>
        <button type="button" className="btn-ghost !px-2 !py-1 text-brand-700" onClick={() => onEdit(step)}>
          <Pencil className="h-3.5 w-3.5" /> Edit
        </button>
      </div>
      {children}
    </section>
  );
}

const Row = ({ label, value }) => (
  <div>
    <dt className="text-xs text-navy-500">{label}</dt>
    <dd className="whitespace-pre-wrap text-sm font-medium">{value?.trim() ? value : <span className="font-normal text-navy-500">Not provided</span>}</dd>
  </div>
);

export default function AssessmentReview({ values, files, onEdit, register, errors }) {
  return (
    <div className="space-y-5">
      <Block title="Patient details" step={0} onEdit={onEdit}>
        <dl className="grid gap-3 sm:grid-cols-3">
          <Row label="Name" value={values.patientName} />
          <Row label="Age" value={values.age ? `${values.age} years` : ''} />
          <Row label="Gender" value={values.gender} />
        </dl>
      </Block>

      <Block title="Symptoms" step={1} onEdit={onEdit}>
        <dl className="space-y-3">
          <Row label="Typed symptoms" value={values.symptoms} />
          <Row label="Voice transcription" value={values.voiceTranscription} />
        </dl>
      </Block>

      <Block title="Medical history" step={0} onEdit={onEdit}>
        <dl className="grid gap-3 sm:grid-cols-2">
          <Row label="Medical conditions" value={values.medicalConditions} />
          <Row label="Current medications" value={values.currentMedications} />
          <Row label="Allergies" value={values.allergies} />
          <Row label="Other history" value={values.medicalHistory} />
        </dl>
      </Block>

      <Block title="Uploaded reports" step={2} onEdit={onEdit}>
        {files.length ? (
          <ul className="space-y-1 text-sm">
            {files.map((f, i) => (
              <li key={i} className="flex justify-between gap-3">
                <span className="truncate">{f.name}</span>
                <span className="shrink-0 text-navy-500">{formatFileSize(f.size)}</span>
              </li>
            ))}
          </ul>
        ) : (
          <p className="text-sm text-navy-500">No reports uploaded.</p>
        )}
      </Block>

      <section className="card border-amber-200 bg-amber-50">
        <h2 className="section-title">Consent</h2>
        <p className="text-sm text-amber-900">
          This assessment is generated by AI and is intended for preliminary informational purposes. It is not a confirmed medical diagnosis.
        </p>
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-amber-900">
          <li>The patient information and any uploaded reports will be processed by an AI service.</li>
          <li>Results are preliminary and do not replace professional medical consultation.</li>
        </ul>
        <label className="mt-4 flex items-start gap-3 text-sm font-medium text-navy-900">
          <input type="checkbox" className="mt-0.5 h-4 w-4 rounded border-slate-400" {...register('consent', { validate: (v) => v || 'You must confirm consent to continue' })} />
          <span>
            I confirm that I have the patient's permission (or am the patient/legal guardian) to submit this information for AI processing, and I understand the limitations above.
          </span>
        </label>
        {errors.consent && <p className="field-error" role="alert">{errors.consent.message}</p>}
      </section>
    </div>
  );
}
